package com.edde746.tortuga.ui.detail

import com.edde746.tortuga.presentation.board.MetaCard
import com.edde746.tortuga.presentation.menu.MediaAction

/** [DetailIntents] for a test: each intent does nothing unless the test gives it. */
internal fun testDetailIntents(
    play: () -> Unit = {},
    chooseStream: () -> Unit = {},
    selectSeason: (Int) -> Unit = {},
    openEpisode: (String) -> Unit = {},
    openLink: (String) -> Unit = {},
    openTrailer: (String) -> Unit = {},
    toggleLibrary: () -> Unit = {},
    markWatched: (Boolean) -> Unit = {},
    seasonMenu: (Int, MediaAction) -> Unit = { _, _ -> },
    episodeMenu: (String, MediaAction) -> Unit = { _, _ -> },
    pressDownload: () -> Unit = {},
    downloadAction: (String) -> Unit = {},
    dismissDownloadNotice: () -> Unit = {},
    confirmDownloadDelete: () -> Unit = {},
    dismissDownloadDelete: () -> Unit = {},
    answerPlayerApp: (Boolean) -> Unit = {},
    episodeShown: () -> Unit = {},
    pickRange: (Int) -> Unit = {},
    share: () -> Unit = {},
    rate: (Int?) -> Unit = {},
    watchlist: () -> Unit = {},
    openRelated: (MetaCard) -> Unit = {},
    relatedMenu: (MetaCard, MediaAction) -> Unit = { _, _ -> },
    reload: () -> Unit = {},
    askParent: () -> Unit = {},
    blockOnProfile: () -> Unit = {},
) = DetailIntents(
    play = play,
    chooseStream = chooseStream,
    selectSeason = selectSeason,
    openEpisode = openEpisode,
    openLink = openLink,
    openTrailer = openTrailer,
    toggleLibrary = toggleLibrary,
    markWatched = markWatched,
    seasonMenu = seasonMenu,
    episodeMenu = episodeMenu,
    pressDownload = pressDownload,
    downloadAction = downloadAction,
    dismissDownloadNotice = dismissDownloadNotice,
    confirmDownloadDelete = confirmDownloadDelete,
    dismissDownloadDelete = dismissDownloadDelete,
    answerPlayerApp = answerPlayerApp,
    episodeShown = episodeShown,
    pickRange = pickRange,
    share = share,
    rate = rate,
    watchlist = watchlist,
    openRelated = openRelated,
    relatedMenu = relatedMenu,
    reload = reload,
    askParent = askParent,
    blockOnProfile = blockOnProfile,
)
