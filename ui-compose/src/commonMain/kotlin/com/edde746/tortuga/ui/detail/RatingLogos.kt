/**
 * A mark of [width] × [height] viewport units (its SVG's viewBox, whose origin is [originX], [originY]), built on first
 * use; 16 dp tall at its intrinsic size, though the row sizes each mark itself.
 */
private fun logo(width: Float, height: Float, originX: Float = 0f, originY: Float = 0f, paths: ImageVector.Builder.() -> Unit) =
    lazy(LazyThreadSafetyMode.NONE) {
        ImageVector.Builder(defaultWidth = (16 * width / height).dp, defaultHeight = 16.dp, viewportWidth = width, viewportHeight = height)
            .apply { if (originX != 0f || originY != 0f) addGroup(translationX = -originX, translationY = -originY) }
            .apply(paths)
            .build()
    }

private fun ImageVector.Builder.path(color: Long, pathData: String) {
    addPath(pathNodes(pathData), fill = SolidColor(Color(color)))
}

private fun ImageVector.Builder.path(fill: Brush, pathData: String) {
    addPath(pathNodes(pathData), fill = fill)
}
