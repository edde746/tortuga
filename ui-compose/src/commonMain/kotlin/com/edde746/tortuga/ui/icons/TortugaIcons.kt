/** A 24 dp icon of one filled path, built on first use. */
private fun icon(pathData: String, autoMirror: Boolean = false) = lazy(LazyThreadSafetyMode.NONE) {
    ImageVector.Builder(defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f, autoMirror = autoMirror)
        .addPath(pathNodes(pathData), fill = SolidColor(Color.Black))
        .build()
}

/**
 * SVG path data as Compose's path nodes, each relative move made absolute: every path the app draws from path data
 * goes through here. Compose hands a relative move to the platform's path as one, and Android 12 and older (Skia's
 * `rMoveTo`) start a move that follows a close from the closed contour's last point, not from its start as SVG does:
 * Skip previous's triangle (`H6zm3.5,6`) drew half the icon low on a Fire TV (Android 11), and TMDB's, AniList's and
 * MDBList's marks drew parts out of place. A contour that ends where it starts (most of Material's) hid it.
 */
internal fun pathNodes(pathData: String): List<PathNode> {
    var x = 0f
    var y = 0f
    var startX = 0f
    var startY = 0f
    return addPathNodes(pathData).map { node ->
        when (node) {
            is PathNode.RelativeMoveTo -> {
                x += node.dx
                y += node.dy
                startX = x
                startY = y
                return@map PathNode.MoveTo(x, y)
            }
            is PathNode.MoveTo -> {
                x = node.x
                y = node.y
                startX = x
                startY = y
            }
            PathNode.Close -> {
                x = startX
                y = startY
            }
            is PathNode.LineTo -> { x = node.x; y = node.y }
            is PathNode.RelativeLineTo -> { x += node.dx; y += node.dy }
            is PathNode.HorizontalTo -> x = node.x
            is PathNode.RelativeHorizontalTo -> x += node.dx
            is PathNode.VerticalTo -> y = node.y
            is PathNode.RelativeVerticalTo -> y += node.dy
            is PathNode.CurveTo -> { x = node.x3; y = node.y3 }
            is PathNode.RelativeCurveTo -> { x += node.dx3; y += node.dy3 }
            is PathNode.ReflectiveCurveTo -> { x = node.x2; y = node.y2 }
            is PathNode.RelativeReflectiveCurveTo -> { x += node.dx2; y += node.dy2 }
            is PathNode.QuadTo -> { x = node.x2; y = node.y2 }
            is PathNode.RelativeQuadTo -> { x += node.dx2; y += node.dy2 }
            is PathNode.ReflectiveQuadTo -> { x = node.x; y = node.y }
            is PathNode.RelativeReflectiveQuadTo -> { x += node.dx; y += node.dy }
            // An arc's "start" is where it ends.
            is PathNode.ArcTo -> { x = node.arcStartX; y = node.arcStartY }
            is PathNode.RelativeArcTo -> { x += node.arcStartDx; y += node.arcStartDy }
        }
        node
    }
}
