def icon_composer(r: Renderer, dark: Art, light: Art) -> None:
    """iOS, iPadOS and macOS: an Icon Composer document, from which actool makes every size, appearance and older-OS
    fallback, and the system draws the Liquid Glass shape, lighting and the tinted and clear looks.

    The background is the fill: the light art's gradient, the dark art's in the dark appearance. Icon Composer draws a
    fill gradient top to bottom and ignores any other direction, so the sources' bounding-box vector is not carried
    over. The glyph is one glass layer: its shape as a white image, coloured by the layer's fill per appearance.
    """
    reset_dir(APPLE_ICON / "Assets")
    glyph = "Glyph.png"
    r.render(document(dark.width, dark.height, [place(dark, 0, 0, 1, background=False)]), APPLE_ICON / "Assets" / glyph,
             1024, 1024, "white")
    icon = {
        "fill-specializations": [
            {"value": icon_gradient(light)},
            {"appearance": "dark", "value": icon_gradient(dark)},
        ],
        "groups": [
            {
                "layers": [
                    {
                        "fill-specializations": [
                            {"value": {"solid": icon_color(foreground_color(light))}},
                            {"appearance": "dark", "value": {"solid": icon_color(foreground_color(dark))}},
                        ],
                        "glass": True,
                        "image-name": glyph,
                        "name": "Glyph",
                    }
                ],
                "shadow": {"kind": "neutral", "opacity": 0.5},
                # Opaque: the cream keeps its contrast against the background.
                "translucency": {"enabled": False, "value": 0.5},
            }
        ],
        "supported-platforms": {"squares": "shared"},
    }
    # Icon Composer's own formatting (sorted keys, " : "), so saving the document in it leaves no diff.
    write_text(APPLE_ICON / "icon.json", json.dumps(icon, indent=2, separators=(",", " : "), sort_keys=True) + "\n")


def icon_gradient(art: Art) -> dict:
    """`art`'s background gradient as an Icon Composer fill, which takes exactly two colours (top, then bottom)."""
    _, stops = art.background_gradient()
    if [offset for offset, _ in stops] != [0.0, 1.0]:
        raise BrandError(f"{art.path}: an Icon Composer fill needs exactly two gradient stops, at 0 and 1")
    return {"linear-gradient": [icon_color(color) for _, color in stops]}


def foreground_color(art: Art) -> str:
    """The one solid colour `art`'s foreground is drawn in (masks aside), as six hex digits."""
    colors = {
        hex_rgb(el.get("fill"))
        for top in art.foreground
        for el in top.iter()
        if el.get("fill") not in (None, "none") and not el.get("fill", "").startswith("url(")
    }
    if len(colors) != 1:
        raise BrandError(f"{art.path}: the foreground must be drawn in one colour, found {sorted(colors)}")
    return colors.pop()


def icon_color(digits: str) -> str:
    """Six hex digits as Icon Composer's colour notation."""
    return "srgb:" + ",".join(f"{int(digits[i : i + 2], 16) / 255:.5f}" for i in (0, 2, 4)) + ",1.00000"


TVOS_BRAND = "App Icon & Top Shelf Image"


def tvos(r: Renderer, art: Art, banner: Art) -> None:
    brand = XCASSETS / f"{TVOS_BRAND}.brandassets"
    # 5:3 layered icon: the art square spans the full height, the background extends sideways.
    width, height = 400.0, 240.0
    x = (width - height) / 2
    scale = height / art.width
    layers = {
        "Front": (place(art, x, 0, scale, background=False), "rgba"),
        "Back": (place(art, x, 0, scale, foreground=False, cover=(width, height)), "rgb"),
    }
    stacks = {"App Icon": [(1, 400, 240), (2, 800, 480)], "App Icon - App Store": [(1, 1280, 768)]}
    for stack, sizes in stacks.items():
        stack_dir = brand / f"{stack}.imagestack"
        for layer, (content, mode) in layers.items():
            layer_dir = stack_dir / f"{layer}.imagestacklayer"
            imageset = layer_dir / "Content.imageset"
            images = []
            for s, px_w, px_h in sizes:
                filename = f"{layer}{'' if s == 1 else f'@{s}x'}.png"
                r.render(document(width, height, [copy.deepcopy(content)]), imageset / filename, px_w, px_h, mode)
                images.append({"filename": filename, "idiom": "tv", "scale": f"{s}x"})
            write_contents(imageset, {"images": images, "info": XCODE_INFO})
            write_contents(layer_dir, {"info": XCODE_INFO})
        write_contents(stack_dir, {"info": XCODE_INFO, "layers": [{"filename": f"{name}.imagestacklayer"} for name in layers]})

    # Top Shelf: the banner at full height, centred, background extended to the wider canvas.
    shelves = {"Top Shelf Image": (1920.0, "TopShelf"), "Top Shelf Image Wide": (2320.0, "TopShelfWide")}
    shelf_height = 720.0
    for name, (shelf_width, stem) in shelves.items():
        scale = shelf_height / banner.height
        x = (shelf_width - banner.width * scale) / 2
        doc = document(shelf_width, shelf_height, [place(banner, x, 0, scale, cover=(shelf_width, shelf_height))])
        imageset = brand / f"{name}.imageset"
        images = []
        for s in (1, 2):
            filename = f"{stem}{'' if s == 1 else f'@{s}x'}.png"
            r.render(doc, imageset / filename, round(shelf_width * s), round(shelf_height * s), "rgb")
            images.append({"filename": filename, "idiom": "tv", "scale": f"{s}x"})
        write_contents(imageset, {"images": images, "info": XCODE_INFO})

