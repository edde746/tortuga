def android(r: Renderer, dark: Art, mono: Art, banner: Art) -> None:
    body = LEGACY_DP - 2 * LEGACY_INSET_DP
    legacy_shapes = {
        "ic_launcher.png": rounded_rect(LEGACY_INSET_DP, LEGACY_INSET_DP, body, LEGACY_CORNER_DP),
        "ic_launcher_round.png": circle(LEGACY_DP / 2, LEGACY_DP / 2, body / 2),
    }
    inset = (ADAPTIVE_CANVAS_DP - ADAPTIVE_VIEWPORT_DP) / 2
    scale = ADAPTIVE_VIEWPORT_DP / dark.width
    layers = {"ic_launcher_foreground.png": dark, "ic_launcher_monochrome.png": mono}
    for qualifier, density in DENSITIES.items():
        mipmap = ANDROID_RES / f"mipmap-{qualifier}"
        px = round(LEGACY_DP * density)
        for filename, shape in legacy_shapes.items():
            art = place(dark, LEGACY_INSET_DP, LEGACY_INSET_DP, body / dark.width)
            r.render(document(LEGACY_DP, LEGACY_DP, clipped(copy.deepcopy(shape), art)), mipmap / filename, px, px)
        px = round(ADAPTIVE_CANVAS_DP * density)
        for filename, art in layers.items():
            layer = place(art, inset, inset, scale, background=False)
            r.render(document(ADAPTIVE_CANVAS_DP, ADAPTIVE_CANVAS_DP, [layer]), mipmap / filename, px, px)

    write_text(ANDROID_RES / "drawable" / "ic_launcher_background.xml", adaptive_background(dark))
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher", "ic_launcher_round"):
        write_text(ANDROID_RES / "mipmap-anydpi-v26" / f"{name}.xml", adaptive)

    # Android TV banner: 160×90 dp at xhdpi.
    r.render(document(banner.width, banner.height, [place(banner, 0, 0, 1)]), ANDROID_RES / "drawable-xhdpi" / "banner.png", 320, 180, "rgb")

    notification_icon(r, mono)


def notification_icon(r: Renderer, art: Art) -> None:
    """The status-bar icon: the glyph around the art's own centre (which keeps its optical balance), scaled so the
    part of it farthest from that centre touches the edge of the live area."""
    scale = NOTIFICATION_LIVE_DP / 2 / glyph_reach(r, art)
    centre = NOTIFICATION_DP / 2
    glyph = place(art, centre - art.width / 2 * scale, centre - art.height / 2 * scale, scale, background=False)
    for qualifier, density in DENSITIES.items():
        px = round(NOTIFICATION_DP * density)
        doc = document(NOTIFICATION_DP, NOTIFICATION_DP, [copy.deepcopy(glyph)])
        r.render(doc, ANDROID_RES / f"drawable-{qualifier}" / "ic_notification.png", px, px, "white")


def foreground_box(r: Renderer, art: Art) -> tuple[int, int, int, int]:
    """The foreground's bounding box (x, y, width, height) in art units, measured on a one-pixel-per-unit render."""
    png = r.workdir / f"{art.name}-foreground.png"
    r.render(document(art.width, art.height, [place(art, 0, 0, 1, background=False)]), png, round(art.width), round(art.height))
    trim = subprocess.run(["magick", str(png), "-format", "%@", "info:"], check=True, capture_output=True, text=True).stdout
    match = re.fullmatch(r"(\d+)x(\d+)\+(\d+)\+(\d+)", trim.strip())
    if not match:
        raise BrandError(f"{art.path}: cannot measure the foreground ({trim!r})")
    w, h, x, y = (int(v) for v in match.groups())
    return x, y, w, h


def glyph_reach(r: Renderer, art: Art) -> float:
    """How far the foreground reaches from the art's centre along either axis, in art units."""
    x, y, w, h = foreground_box(r, art)
    cx, cy = art.width / 2, art.height / 2
    return max(cx - x, x + w - cx, cy - y, y + h - cy)


def adaptive_background(art: Art) -> str:
    """The icon's background gradient as a VectorDrawable over the 108 dp canvas.

    The gradient vector spans the 72 dp viewport, where the source's bounding box lands, and
    clamps beyond it.
    """
    (x1, y1, x2, y2), stops = art.background_gradient()
    inset = (ADAPTIVE_CANVAS_DP - ADAPTIVE_VIEWPORT_DP) / 2

    def to_dp(fraction: float) -> str:
        return fmt(inset + fraction * ADAPTIVE_VIEWPORT_DP)

    items = "".join(
        f'                <item android:offset="{fmt(offset)}" android:color="#FF{color}" />\n'
        for offset, color in stops
    )
    size = fmt(ADAPTIVE_CANVAS_DP)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        f'    android:width="{size}dp"\n'
        f'    android:height="{size}dp"\n'
        f'    android:viewportWidth="{size}"\n'
        f'    android:viewportHeight="{size}">\n'
        f'    <path android:pathData="M0,0h{size}v{size}h-{size}z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        "            <gradient\n"
        '                android:type="linear"\n'
        '                android:tileMode="clamp"\n'
        f'                android:startX="{to_dp(x1)}"\n'
        f'                android:startY="{to_dp(y1)}"\n'
        f'                android:endX="{to_dp(x2)}"\n'
        f'                android:endY="{to_dp(y2)}">\n'
        f"{items}"
        "            </gradient>\n"
        "        </aapt:attr>\n"
        "    </path>\n"
        "</vector>\n"
    )


