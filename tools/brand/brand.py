class BrandError(Exception):
    pass


def q(tag: str) -> str:
    return f"{{{SVG_NS}}}{tag}"


def fmt(value: float) -> str:
    """Shortest stable decimal for SVG/XML attributes."""
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


class Art:
    """One brand SVG, split into its background rect and foreground elements."""

    def __init__(self, name: str):
        self.name = name
        self.path = BRAND / f"{name}.svg"
        root = ET.parse(self.path).getroot()
        x0, y0, self.width, self.height = (float(v) for v in root.get("viewBox", "").split())
        if (x0, y0) != (0.0, 0.0):
            raise BrandError(f"{self.path}: viewBox must start at 0 0")
        self.defs = [el for el in root if el.tag == q("defs")]
        backgrounds = [el for el in root if el.tag == q("rect") and self._covers_canvas(el)]
        if len(backgrounds) != 1:
            raise BrandError(f"{self.path}: expected exactly one full-canvas background <rect>")
        self.background = backgrounds[0]
        self.foreground = [el for el in root if el.tag != q("defs") and el is not self.background]
        if not self.foreground:
            raise BrandError(f"{self.path}: no foreground elements")

    def _covers_canvas(self, el: ET.Element) -> bool:
        return (
            float(el.get("x", "0")) == 0
            and float(el.get("y", "0")) == 0
            and float(el.get("width", "0")) == self.width
            and float(el.get("height", "0")) == self.height
        )

    def background_gradient(self) -> tuple[list[float], list[tuple[float, str]]]:
        """The background's linear gradient as [x1, y1, x2, y2] in bounding-box units and its stops."""
        match = re.fullmatch(r"url\(#([^)]+)\)", self.background.get("fill", ""))
        if not match:
            raise BrandError(f"{self.path}: background fill is not a gradient reference")
        gradient = next(
            (el for d in self.defs for el in d.iter(q("linearGradient")) if el.get("id") == match.group(1)),
            None,
        )
        if gradient is None:
            raise BrandError(f"{self.path}: gradient #{match.group(1)} not found")
        unsupported = {"gradientUnits", "gradientTransform", "spreadMethod"} & set(gradient.keys())
        if unsupported or any(key.endswith("href") for key in gradient.keys()):
            raise BrandError(f"{self.path}: gradient must be a plain bounding-box gradient")
        vector = [_number(gradient.get(k, d)) for k, d in (("x1", "0"), ("y1", "0"), ("x2", "1"), ("y2", "0"))]
        stops = []
        for stop in gradient.iter(q("stop")):
            if stop.get("stop-opacity", "1") != "1":
                raise BrandError(f"{self.path}: translucent gradient stops are not supported")
            stops.append((_number(stop.get("offset", "0")), hex_rgb(stop.get("stop-color", "#000"))))
        return vector, stops


def _number(value: str) -> float:
    """An SVG number or percentage as a fraction."""
    return float(value[:-1]) / 100 if value.endswith("%") else float(value)


def place(
    art: Art,
    x: float,
    y: float,
    scale: float,
    *,
    background: bool = True,
    foreground: bool = True,
    cover: tuple[float, float] | None = None,
    gray: bool = False,
) -> ET.Element:
    """`art` with its origin at (x, y) and `scale` design units per art unit.

    `cover=(w, h)` grows the background rect (never the art) to fill a w×h design canvas; the
    bounding-box gradient follows the rect, which is how the sources themselves fill 16:9.
    """
    group = ET.Element(q("g"), transform=f"translate({fmt(x)} {fmt(y)}) scale({fmt(scale)})")
    for d in art.defs:
        group.append(copy.deepcopy(d))
    if background:
        rect = copy.deepcopy(art.background)
        if cover is not None:
            rect.set("x", fmt(-x / scale))
            rect.set("y", fmt(-y / scale))
            rect.set("width", fmt(cover[0] / scale))
            rect.set("height", fmt(cover[1] / scale))
        group.append(rect)
    if foreground:
        for el in art.foreground:
            group.append(copy.deepcopy(el))
    if gray:
        _grayscale(group)
    return group


_COLOR_ATTRS = ("fill", "stroke", "stop-color", "flood-color", "lighting-color", "color")


def hex_rgb(value: str) -> str:
    """`#RGB`/`#RRGGBB` as six uppercase hex digits."""
    match = re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})", value)
    if not match:
        raise BrandError(f"unsupported colour {value!r}")
    digits = match.group(1).upper()
    return "".join(c * 2 for c in digits) if len(digits) == 3 else digits


def _grayscale(tree: ET.Element) -> None:
    """Replace every colour with its Rec. 709 luma grey (what CSS grayscale(1) does)."""
    for el in tree.iter():
        for attr in _COLOR_ATTRS:
            value = el.get(attr)
            if value is None or value == "none" or value.startswith("url("):
                continue
            digits = hex_rgb(value)
            r, g, b = (int(digits[i : i + 2], 16) for i in (0, 2, 4))
            luma = round(0.2126 * r + 0.7152 * g + 0.0722 * b)
            el.set(attr, f"#{luma:02X}{luma:02X}{luma:02X}")


def rounded_rect(x: float, y: float, size: float, radius: float) -> ET.Element:
    return ET.Element(
        q("rect"), x=fmt(x), y=fmt(y), width=fmt(size), height=fmt(size), rx=fmt(radius), ry=fmt(radius)
    )


def circle(cx: float, cy: float, r: float) -> ET.Element:
    return ET.Element(q("circle"), cx=fmt(cx), cy=fmt(cy), r=fmt(r))


def clipped(shape: ET.Element, content: ET.Element) -> list[ET.Element]:
    defs = ET.Element(q("defs"))
    clip = ET.SubElement(defs, q("clipPath"), id="tortuga-clip")
    clip.append(shape)
    wrapper = ET.Element(q("g"), {"clip-path": "url(#tortuga-clip)"})
    wrapper.append(content)
    return [defs, wrapper]


def document(width: float, height: float, children: list[ET.Element]) -> ET.Element:
    """An SVG document with a `width`×`height` design-unit viewBox; pixel size is chosen at render time."""
    root = ET.Element(q("svg"), width=fmt(width), height=fmt(height), viewBox=f"0 0 {fmt(width)} {fmt(height)}")
    root.extend(children)
    return root


class Renderer:
    def __init__(self, workdir: Path):
        self.workdir = workdir
        self.count = 0

    def render(self, doc: ET.Element, out: Path, width: int, height: int, mode: str = "rgba") -> None:
        """Render `doc` to a `width`×`height` PNG.

        mode: rgba, rgba32 (an alpha channel even where every pixel is opaque, which rsvg-convert leaves out), rgb
        (opaque, no alpha), gray, or white (every pixel white, keeping the rendering's alpha).
        """
        self.count += 1
        svg = self.workdir / f"{self.count}.svg"
        ET.ElementTree(doc).write(svg, encoding="utf-8", xml_declaration=True)
        out.parent.mkdir(parents=True, exist_ok=True)
        png = out if mode == "rgba" else self.workdir / f"{self.count}.png"
        subprocess.run(
            ["rsvg-convert", "--width", str(width), "--height", str(height), "--output", str(png), str(svg)],
            check=True,
        )
        if mode == "rgba":
            return
        if mode == "rgba32":
            conversion = ["-alpha", "on", "-define", "png:color-type=6"]
        elif mode == "rgb":
            conversion = ["-alpha", "off", "-type", "TrueColor", "-define", "png:color-type=2"]
        elif mode == "gray":
            conversion = ["-alpha", "off", "-colorspace", "Gray", "-type", "Grayscale", "-define", "png:color-type=0"]
        elif mode == "white":
            conversion = ["-fill", "white", "-colorize", "100", "-define", "png:color-type=6"]
        else:
            raise BrandError(f"unknown render mode {mode}")
        subprocess.run(
            ["magick", str(png), *conversion, "-strip", "-define", "png:exclude-chunks=date,time", str(out)],
            check=True,
        )


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_contents(directory: Path, contents: dict) -> None:
    """Contents.json in Xcode's own formatting, so opening the catalog in Xcode leaves no diff."""
    write_text(directory / "Contents.json", json.dumps(contents, indent=2, separators=(",", " : ")) + "\n")


XCODE_INFO = {"author": "xcode", "version": 1}


def reset_dir(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)


