# ---------------------------------------------------------------- Desktop


def desktop_icon(art: Art, x: float = 0.0) -> list[ET.Element]:
    """The Windows and Linux icon in `art` units, its left edge at `x`: the art in a rounded square with a margin."""
    margin = art.width * DESKTOP_MARGIN
    body = art.width - 2 * margin
    shape = rounded_rect(x + margin, margin, body, body * DESKTOP_CORNER_RATIO)
    return clipped(shape, place(art, x + margin, margin, body / art.width))


def desktop(r: Renderer, art: Art) -> None:
    reset_dir(DESKTOP_ICONS)
    doc = document(art.width, art.height, desktop_icon(art))

    r.render(doc, DESKTOP_ICONS / "tortuga.png", 512, 512)
    for size in HICOLOR_SIZES:
        r.render(doc, DESKTOP_ICONS / "hicolor" / f"{size}x{size}" / "apps" / f"{APP_ID}.png", size, size)

    entries = []
    for size in ICO_SIZES:
        png = r.workdir / f"ico-{size}.png"
        r.render(doc, png, size, size)
        entries.append((size, png.read_bytes()))
    write_ico(DESKTOP_ICONS / "tortuga.ico", entries)

    reset_dir(MSIX_ASSETS)
    for name, (width, height) in MSIX_SIZES.items():
        canvas = art.height * width / height
        doc = document(canvas, art.height, desktop_icon(art, (canvas - art.width) / 2))
        r.render(doc, MSIX_ASSETS / f"{name}.png", width, height)


def write_ico(path: Path, entries: list[tuple[int, bytes]]) -> None:
    """ICO with one PNG-compressed 32-bit entry per size (supported since Windows Vista)."""
    header = struct.pack("<HHH", 0, 1, len(entries))
    offset = len(header) + 16 * len(entries)
    directory = b""
    for size, data in entries:
        dim = 0 if size >= 256 else size  # 0 encodes 256
        directory += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    path.write_bytes(header + directory + b"".join(data for _, data in entries))


# ---------------------------------------------------------------- Store listings


def store(r: Renderer, dark: Art, banner: Art) -> None:
    """The listing graphics no screenshot covers. Play's hi-res icon and Amazon's icons are the full-bleed square
    (each store draws its own shape) as the 32-bit PNG both ask for; mode rgb (24-bit, no alpha) where the store
    refuses transparency."""
    square = document(dark.width, dark.height, [place(dark, 0, 0, 1)])
    for out, px in ((PLAY_IMAGES / "icon.png", 512), (AMAZON_IMAGES / "icon-small.png", 114), (AMAZON_IMAGES / "icon-large.png", 512)):
        r.render(square, out, px, px, "rgba32")

    box = foreground_box(r, banner)
    # Play's feature graphic, also Amazon's promotional image: the banner's mark and name in the middle 70 % × 64 %,
    # clear of the edges Play may crop and at least 50 px from each edge (Amazon's rule for its text).
    feature = wordmark(banner, box, 1024, 500, 0.70 * 1024, 0.64 * 500)
    r.render(feature, PLAY_IMAGES / "featureGraphic.png", 1024, 500, "rgb")
    r.render(feature, AMAZON_IMAGES / "promo.png", 1024, 500, "rgb")
    # Play's Android TV banner: the app's own banner (drawable-xhdpi/banner.png) at Play's 1280×720.
    r.render(document(banner.width, banner.height, [place(banner, 0, 0, 1)]), PLAY_IMAGES / "tvBanner.png", 1280, 720, "rgb")
    # Fire TV's app icon: the mark and name inside Amazon's 882×448 content-safe area, where no badge covers them.
    r.render(wordmark(banner, box, 1280, 720, 882, 448), AMAZON_IMAGES / "firetv-icon.png", 1280, 720, "rgb")

    # Fire TV's background takes no logo or title: the icon's gradient alone. Microsoft's 16:9 Super hero art takes no
    # text: the glyph right of centre (where the Store's text overlays leave it alone) on the same gradient.
    width, height = 1920.0, 1080.0
    scale = 0.75 * height / dark.height
    x, y = 0.68 * width - dark.width * scale / 2, (height - dark.height * scale) / 2
    gradient = document(width, height, [place(dark, x, y, scale, foreground=False, cover=(width, height))])
    r.render(gradient, AMAZON_IMAGES / "firetv-background.png", 1920, 1080, "rgb")
    r.render(document(width, height, [place(dark, x, y, scale, cover=(width, height))]), MICROSOFT_IMAGES / "super-hero-art.png", 1920, 1080, "rgb")
    # Microsoft's 1:1 app tile icon, which the Store shows instead of the package's: the desktop icon.
    r.render(document(dark.width, dark.height, desktop_icon(dark)), MICROSOFT_IMAGES / "app-tile-icon.png", 300, 300)


def wordmark(banner: Art, box: tuple[int, int, int, int], width: float, height: float, fit_w: float, fit_h: float) -> ET.Element:
    """A width×height canvas with the banner's foreground (its mark and name, measured as `box`) scaled to fit
    fit_w×fit_h and centred, the banner's background extended to the canvas."""
    x0, y0, w, h = box
    scale = min(fit_w / w, fit_h / h)
    x = (width - w * scale) / 2 - x0 * scale
    y = (height - h * scale) / 2 - y0 * scale
    return document(width, height, [place(banner, x, y, scale, cover=(width, height))])


def main() -> int:
    dark = Art("tortuga-icon-dark")
    light = Art("tortuga-icon-light")
    mono = Art("tortuga-icon-mono")
    banner = Art("tortuga-tv-banner-dark")
    for icon in (dark, light, mono):
        if icon.width != icon.height:
            raise BrandError(f"{icon.path}: app icon must be square")
    with tempfile.TemporaryDirectory(prefix="tortuga-brand-") as tmp:
        r = Renderer(Path(tmp))
        android(r, dark, mono, banner)
        apple(r, dark, light, banner)
        desktop(r, dark)
        store(r, dark, banner)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (BrandError, subprocess.CalledProcessError) as error:
        print(f"brand: {error}", file=sys.stderr)
        sys.exit(1)
