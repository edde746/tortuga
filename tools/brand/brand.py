"""Regenerates Tortuga's platform icons and TV art from the SVG sources in tools/brand/.

Run through tools/brand/generate.sh, which checks the toolchain first.

Every output is derived from the structure of the sources: the full-canvas <rect> directly
under <svg> is the background layer, every other drawable element is the foreground layer.
Compositions are built as SVG in design units (dp, pt or source units) and rendered once
per pixel size with rsvg-convert, so no output is resampled from another bitmap.
"""
