package tortuga.buildlogic.strings

/**
 * Renders a [Catalog] as Kotlin in [PACKAGE], next to the handwritten runtime it calls
 * (`shared/src/commonMain/kotlin/com/edde746/tortuga/strings/`: `LocaleTable`, `PluralCategory`).
 *
 * Files, relative to the source root:
 * - `.../strings/T.kt`: `object T` (`locale`, top-level strings, one getter per top-level group) and
 *   `internal object Locales`, one index constant per locale file.
 * - `.../strings/<Group>Strings.kt` per top-level group: `object <Group>Strings` plus its nested groups, each an
 *   object named after its full path (`player.menu` → `PlayerMenuStrings`).
 *
 * A string with no parameters is a `val`; one with `${…}` parameters a `fun` taking them as `String`s in order of first
 * appearance in English; a plural a `fun` taking `n: Int` first. Each accessor tries the selected locale chain
 * (`Locales.chain`) and ends in English, so a key missing from a translation falls back per key.
 */
internal object KotlinRenderer {
    const val PACKAGE = "com.edde746.tortuga.strings"
    private const val HEADER = "// Generated by build-logic's tortuga.strings plugin from shared/i18n/*.i18n.json. Edit those files, not this one."
    private const val LOCALE_VAR = "_locale" // Keys and parameters start with a lowercase letter, so nothing shadows it.

    fun render(catalog: Catalog): Map<String, String> {
        val classNames = classNames(catalog.base)
        val dir = PACKAGE.replace('.', '/')
        val files = LinkedHashMap<String, String>()
        val translations = catalog.locales.drop(1).map { it to it.root }

        files["$dir/T.kt"] = file {
            line("/**")
            line(" * Every user-visible string, generated from `i18n/<locale>.i18n.json`: `T.player.play`,")
            line(" * `T.player.error.http(status)`, `T.player.track.channels(n)`. Views render these; they never format.")
            line(" */")
            block("object T") {
                line("/**")
                line(" * The UI language as a BCP 47 tag (`de`, `pt-BR`, `zh-Hant-TW`; `_` also works as a separator); `en` by")
                line(" * default. Each string comes from the most specific locale file that has it (`pt-BR`, then `pt`), else")
                line(" * English. Plural forms follow the CLDR rules of the language the chosen text is written in.")
                line(" */")
                line("var locale: String")
                line("    get() = Locales.tag")
                line("    set(value) = Locales.select(value)")
                members(path = "", catalog.base.root, translations, classNames)
            }
            line()
            line("/** Index of each locale file in [LocaleTable], English first. */")
            block("internal object Locales : LocaleTable(arrayOf(${catalog.locales.joinToString { "\"${it.tag}\"" }}))") {
                catalog.locales.forEachIndexed { index, locale -> line("const val ${constant(locale)} = $index") }
            }
        }
        for ((key, node) in catalog.base.root.children) {
            if (node !is Node.Group) continue
            files["$dir/${classNames.getValue(key)}.kt"] = file { groupObjects(key, node, translations.child(key), classNames) }
        }
        return files
    }

    /** `object` for the group at [path], then its nested groups, depth first. */
    private fun Code.groupObjects(path: String, group: Node.Group, translations: List<Pair<Locale, Node.Group>>, classNames: Map<String, String>) {
        block("object ${classNames.getValue(path)}") { members(path, group, translations, classNames) }
        for ((key, node) in group.children) {
            if (node !is Node.Group) continue
            line()
            groupObjects(join(path, key), node, translations.child(key), classNames)
        }
    }

    private fun Code.members(path: String, group: Node.Group, translations: List<Pair<Locale, Node.Group>>, classNames: Map<String, String>) {
        for ((key, node) in group.children) {
            line()
            when (node) {
                is Node.Group -> classNames.getValue(join(path, key)).let { line("val $key: $it get() = $it") }
                is Node.Text -> text(key, node, translations.mapNotNull { (locale, g) -> (g.children[key] as Node.Text?)?.let { locale to it } })
                is Node.Plural -> plural(key, node, translations.mapNotNull { (locale, g) -> (g.children[key] as Node.Plural?)?.let { locale to it } })
            }
        }
    }

    private fun Code.text(key: String, english: Node.Text, translated: List<Pair<Locale, Node.Text>>) {
        doc(english.template)
        val params = english.template.params
        val declaration = if (params.isEmpty()) "val $key: String" else "fun $key(${params.joinToString { "$it: String" }}): String"
        when {
            translated.isEmpty() && params.isEmpty() -> line("$declaration get() = ${literal(english.template)}")
            translated.isEmpty() -> line("$declaration = ${literal(english.template)}")
            else -> {
                val body: Code.() -> Unit = {
                    block("for ($LOCALE_VAR in Locales.chain) when ($LOCALE_VAR)") {
                        for ((locale, node) in translated) line("Locales.${constant(locale)} -> return ${literal(node.template)}")
                    }
                    line("return ${literal(english.template)}")
                }
                if (params.isEmpty()) {
                    line(declaration)
                    indented { block("get()", body) }
                } else {
                    block(declaration, body)
                }
            }
        }
    }

    private fun Code.plural(key: String, english: Node.Plural, translated: List<Pair<Locale, Node.Plural>>) {
        doc(english.forms.getValue(PluralCategory.OTHER))
        val declaration = "fun $key(${(listOf("$COUNT: Int") + english.params.map { "$it: String" }).joinToString()}): String"
        if (translated.isEmpty()) {
            line("$declaration =")
            indented { pluralExpression("", "Locales.${constant(BASE_TAG)}", english) }
            return
        }
        block(declaration) {
            block("for ($LOCALE_VAR in Locales.chain) when ($LOCALE_VAR)") {
                for ((locale, node) in translated) pluralExpression("Locales.${constant(locale)} -> return ", LOCALE_VAR, node)
            }
            pluralExpression("return ", "Locales.${constant(BASE_TAG)}", english)
        }
    }

    /** `[prefix]<forms of [plural] chosen by the plural rules of [locale]>`; a lone `other` needs no rules. */
    private fun Code.pluralExpression(prefix: String, locale: String, plural: Node.Plural) {
        if (plural.forms.size == 1) {
            line(prefix + literal(plural.forms.getValue(PluralCategory.OTHER)))
            return
        }
        block("${prefix}when (Locales.plural($locale, $COUNT))") {
            for ((category, template) in plural.forms.toSortedMap()) {
                line("${if (category == PluralCategory.OTHER) "else" else "PluralCategory.$category"} -> ${literal(template)}")
            }
        }
    }

    private fun Code.doc(template: Template) {
        val text = template.parts.joinToString("") {
            when (it) {
                is Template.Part.Literal -> it.text
                is Template.Part.Param -> "\${${it.name}}"
            }
        }
        // Kotlin comments nest, so neither `/*` nor `*/` may appear; U+2215 looks like a slash.
        val safe = text.map { if (it.isISOControl()) ' ' else it }.joinToString("").replace("*/", "*\u2215").replace("/*", "\u2215*")
        line("/** \"$safe\" */")
    }

    /** A Kotlin string literal: parameters as `${name}` templates, everything else escaped to mean itself. */
    private fun literal(template: Template): String = buildString {
        append('"')
        for (part in template.parts) {
            when (part) {
                is Template.Part.Param -> append("\${").append(part.name).append('}')
                is Template.Part.Literal -> escape(part.text)
            }
        }
        append('"')
    }

    private fun StringBuilder.escape(text: String) {
        var i = 0
        while (i < text.length) {
            val c = text[i]
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '$' -> append("\\$")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c.isHighSurrogate() && i + 1 < text.length && text[i + 1].isLowSurrogate() -> append(c).append(text[++i])
                // Lone surrogates can't be written as UTF-8; controls and invisible format characters are escaped too.
                c.isSurrogate() || c.isISOControl() || Character.getType(c).toByte().let {
                    it == Character.FORMAT || it == Character.LINE_SEPARATOR || it == Character.PARAGRAPH_SEPARATOR
                } -> append("\\u%04X".format(c.code))
                else -> append(c)
            }
            i++
        }
    }

    /** Class name per group path; two paths that would share one (`a.bC`, `aB.c`) fail the build. */
    private fun classNames(base: Locale): Map<String, String> {
        val byPath = LinkedHashMap<String, String>()
        val byName = HashMap<String, String>()
        val errors = mutableListOf<String>()
        fun visit(path: String, group: Node.Group) {
            for ((key, node) in group.children) {
                if (node !is Node.Group) continue
                val childPath = join(path, key)
                val name = childPath.split('.').joinToString("") { it.replaceFirstChar(Char::uppercaseChar) } + "Strings"
                byName.put(name, childPath)?.let {
                    errors += "${base.source}:${node.line}: $childPath: generates class $name, as does $it; rename one of them"
                }
                byPath[childPath] = name
                visit(childPath, node)
            }
        }
        visit("", base.root)
        if (errors.isNotEmpty()) throw StringsException(errors.joinToString("\n"))
        return byPath
    }

    private fun List<Pair<Locale, Node.Group>>.child(key: String) = mapNotNull { (locale, group) ->
        (group.children[key] as Node.Group?)?.let { locale to it }
    }

    private fun constant(locale: Locale) = constant(locale.tag)

    private fun constant(tag: String) = tag.uppercase().replace('-', '_')

    private fun join(path: String, key: String) = if (path.isEmpty()) key else "$path.$key"

    private fun file(content: Code.() -> Unit): String = Code().apply {
        line(HEADER)
        line("package $PACKAGE")
        line()
        content()
    }.toString()

    private class Code {
        private val out = StringBuilder()
        private var indent = 0

        fun line(text: String = "") {
            if (text.isEmpty()) {
                // No blank line right after an opening brace.
                if (!out.endsWith("{\n")) out.append('\n')
            } else {
                repeat(indent) { out.append("    ") }
                out.append(text).append('\n')
            }
        }

        fun block(header: String, body: Code.() -> Unit) {
            line("$header {")
            indented(body)
            line("}")
        }

        fun indented(body: Code.() -> Unit) {
            indent++
            body()
            indent--
        }

        override fun toString() = out.toString()
    }
}
